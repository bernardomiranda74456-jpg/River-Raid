// Builds a single self-contained HTML file (../wobble-rush.html) with all
// game modules, Three.js, its addons, Rapier (WASM inlined) and the CSS.
// Usage: node tools/build-single.mjs   (needs esbuild: npm i -D esbuild)
import { build } from 'esbuild';
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(new URL('..', import.meta.url).pathname);
const out = path.resolve(root, '..', 'wobble-rush.html');

const result = await build({
  entryPoints: [path.join(root, 'src/main.js')],
  bundle: true, format: 'esm', target: 'es2020', minify: true, write: false, legalComments: 'none',
  alias: {
    three: path.join(root, 'vendor/three/three.module.js'),
    '@dimforge/rapier3d-compat': path.join(root, 'vendor/rapier/rapier.mjs'),
  },
  plugins: [{
    name: 'three-addons',
    setup(b) { b.onResolve({ filter: /^three\/addons\// }, (a) => ({ path: path.join(root, 'vendor/three/addons', a.path.slice('three/addons/'.length)) })); },
  }],
});
let js = result.outputFiles[0].text.replace(/<\/script/gi, '<\\/script');
const css = fs.readFileSync(path.join(root, 'src/ui/ui.css'), 'utf8');
let html = fs.readFileSync(path.join(root, 'index.html'), 'utf8');
html = html.replace(/<link rel="stylesheet" href="\.\/src\/ui\/ui\.css">/, () => `<style>\n${css}\n</style>`);
html = html.replace(/<script type="importmap">[\s\S]*?<\/script>\s*/, '');
html = html.replace(/<script type="module" src="\.\/src\/main\.js"><\/script>/, () => `<script type="module">\n${js}\n</script>`);
html = html.replace('<head>', '<head>\n  <!-- Wobble Rush — single-file build. Source: tumble-rush/ (Three.js MIT, Rapier Apache-2.0). Generated by tools/build-single.mjs -->');
if (html.includes('src="./src/') || html.includes('href="./src/')) throw new Error('external reference left in HTML');
fs.writeFileSync(out, html);
console.log('wrote', out, (fs.statSync(out).size / 1048576).toFixed(2) + ' MB');
