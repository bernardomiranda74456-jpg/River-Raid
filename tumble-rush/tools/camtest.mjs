// Verifies the follow / first-person cameras: holding D turns the character and the camera follows.
import { chromium } from 'playwright';
import { spawn } from 'node:child_process';
import path from 'node:path';
const root = path.resolve(new URL('..', import.meta.url).pathname);
const out = process.argv[2] || path.join(root, 'screenshots');
const port = 8799;
const server = spawn('python3', ['-m', 'http.server', String(port), '--bind', '127.0.0.1'], { cwd: root, stdio: 'ignore' });
await new Promise((r) => setTimeout(r, 700));
const browser = await chromium.launch({ headless: true, executablePath: '/opt/pw-browsers/chromium-1194/chrome-linux/chrome', args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist', '--no-sandbox'] });
const page = await browser.newPage({ viewport: { width: 1280, height: 720 } });
const logs = [];
page.on('console', (m) => { if (['error', 'warning'].includes(m.type())) logs.push(`[${m.type()}] ${m.text()}`); });
page.on('pageerror', (e) => logs.push(`[pageerror] ${e.message}`));
await page.goto(`http://127.0.0.1:${port}/index.html`);
await page.waitForFunction(() => window.__game, null, { timeout: 60000 });
const ev = (f, a) => page.evaluate(f, a);
const frames = (n) => ev((n) => new Promise((res) => { const g = window.__game; const t = g.frame + n; const c = () => (g.frame >= t ? res() : setTimeout(c, 50)); c(); }), n);
const state = (label) => ev((label) => { const g = window.__game; const p = g.player; const deg = (r) => Math.round(((r * 180 / Math.PI) % 360 + 540) % 360 - 180);
  const camYaw = g.tpc.yaw - Math.PI; const d = g.camera.getWorldDirection(new (g.camera.position.constructor)());
  return `${label}: heading=${deg(g.heading)} bonecoYaw=${deg(p.yaw)} cameraAtrasDe=${deg(camYaw)} olhar=${deg(Math.atan2(d.x, d.z))} pos=(${p.pos.x.toFixed(1)}, ${p.pos.y.toFixed(1)}, ${p.pos.z.toFixed(1)}) vivo=${!p.eliminated} cabeçaOculta=${!!p.hideHead}`; }, label);
const shot = async (name) => {
  await ev(() => { const g = window.__game; g.testDt = 0.00001; g.skipRender = false; g.settings.applyPreset('high'); });
  await frames(3); await page.screenshot({ path: path.join(out, name + '.png'), timeout: 240000 }); console.log('shot', name);
  await ev(() => { const g = window.__game; g.settings.applyPreset('low'); g.testDt = 1 / 20; g.skipRender = true; });
};
await ev(() => { const g = window.__game; g.settings.applyPreset('low'); g.testDt = 1 / 20; g.skipRender = true; g.settings.camMode = 'follow'; });
await page.click('#btn-play');
await page.waitForFunction(() => window.__game.state === 'racing', null, { timeout: 120000 });
await frames(10); console.log(await state('início'));
await page.keyboard.down('KeyD'); await frames(10); console.log(await state('D parado 0,5 s (vira no lugar)'));
await frames(10); console.log(await state('D parado 1,0 s'));
await page.keyboard.up('KeyD'); await frames(6); console.log(await state('solto'));
await page.keyboard.down('KeyA'); await frames(20); await page.keyboard.up('KeyA'); await frames(6); console.log(await state('A 1,0 s'));
await page.keyboard.down('KeyW'); await frames(20); console.log(await state('W 1,0 s'));
await page.keyboard.down('KeyD'); await frames(8); console.log(await state('W+D 0,4 s'));
await page.keyboard.up('KeyD'); await frames(6); await page.keyboard.up('KeyW'); console.log(await state('parado'));
await shot('cam-follow');
await page.keyboard.press('KeyV'); await frames(4); console.log('modo:', await ev(() => window.__game.settings.camMode));
console.log(await state('1ª pessoa'));
await page.keyboard.down('KeyA'); await frames(8); await page.keyboard.up('KeyA'); await frames(4); console.log(await state('1ª pessoa +A 0,4 s'));
await shot('cam-first');
await page.keyboard.press('KeyV'); await frames(2); console.log('modo:', await ev(() => window.__game.settings.camMode));
await page.keyboard.press('KeyV'); await frames(2); console.log('modo:', await ev(() => window.__game.settings.camMode));
console.log('console messages:', logs.length); logs.slice(0, 10).forEach((l) => console.log(l));
await browser.close(); server.kill();
