const ACCENTED = { Á: ['A', '´'], À: ['A', '`'], Ã: ['A', '~'], Â: ['A', '^'], É: ['E', '´'], Ê: ['E', '^'], Í: ['I', '´'], Ó: ['O', '´'], Ô: ['O', '^'], Õ: ['O', '~'], Ú: ['U', '´'], Ü: ['U', '¨'] };
const CEDIL = ['.####', '#....', '#....', '#....', '.####', '..#..']; // Ç ocupa 7 linhas (cauda na linha 7)

/** Retorna matriz 8×8 do caractere (letra em maiúsculas; minúsculas são convertidas). */
export function glyph(ch) {
  const c = ch.toUpperCase();
  const rows = Array(8).fill('........');
  let base = G[c], acc = null;
  if (ACCENTED[c]) { base = G[ACCENTED[c][0]]; acc = ACC[ACCENTED[c][1]]; }
  if (c === 'Ç') { base = CEDIL; }
  if (!base) base = G['?'];
  for (let i = 0; i < 6; i++) rows[2 + i] = base[i] + '...';
  if (c === 'Ç') rows[7] = '..#.....';
  if (acc) { rows[0] = acc[0] + '...'; rows[1] = acc[1] + '...'; }
  return rows;
}
export const FONT_CHARS = Object.keys(G).concat(Object.keys(ACCENTED), ['Ç']);
