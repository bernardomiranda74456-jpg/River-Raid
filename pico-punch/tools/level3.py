chunks = [(m1, d1), (m2, d2), (m3, d3), (m4, d4), (m5, d5)]
H = 16
for ci, (m, d) in enumerate(chunks):
    assert len(m) == H and len(d) == H, ('altura', ci, len(m), len(d))
    for i, r in enumerate(m): assert len(r) == CW, ('mapa', ci, i, len(r))
    for i, r in enumerate(d): assert len(r) == CW, ('decor', ci, i, len(r))
rows = [''.join(m[y] for m, _ in chunks) for y in range(H)]
decor = [''.join(d[y] for _, d in chunks) for y in range(H)]
W = CW * len(chunks)
SOLID = set('#%SR?UXI')
WATER = set('~w')
assert all(r[0] == '#' for r in rows)
assert sum(r.count('P') for r in rows) == 1 and sum(r.count('E') for r in rows) == 1
# consistência da água: `~` só no topo de uma coluna d'água, `w` sempre com água acima, nada d'água flutuando
for x in range(W):
    for y in range(H):
        c = rows[y][x]
        if c in WATER or c in 'fj$&H':
            above = rows[y - 1][x] if y > 0 else '.'
            below = rows[y + 1][x] if y + 1 < H else '#'
            if c == '~': assert above not in WATER, ('~ com água acima', x, y)
            if c == 'w': assert above in WATER or above in SOLID or above in 'fj$&H', ('w sob o ar', x, y)
            if c in WATER: assert below in WATER or below in SOLID or below in 'fj$&H', ('água flutuando', x, y)

# Entidades dentro d'água (peixes, águas-vivas, sacos) não podem ficar como caractere no mapa: o char substitui
# o tile e abre um "buraco" de ar na água. Elas vão para a lista "entities" e o tile volta a ser água.
ENT = {'f': 'fish', 'j': 'jelly', '$': 'moneybag', '&': 'bigbag'}
entities = []
grid = [list(r) for r in rows]
for y in range(H):
    for x in range(W):
        c = grid[y][x]
        if c in ENT:
            above = grid[y - 1][x] if y > 0 else '.'
            below = grid[y + 1][x] if y + 1 < H else '#'
            if above in WATER or below in WATER:
                entities.append({"type": ENT[c], "x": x, "y": y})
                grid[y][x] = 'w' if above in WATER else '~'
            elif c in 'fj':
                raise AssertionError(('peixe/água-viva fora d\'água', x, y))
rows = [''.join(r) for r in grid]
for x in range(W):
    for y in range(H):
        c = rows[y][x]
        if c == '~': assert y == 0 or rows[y - 1][x] not in WATER, ('~ com água acima', x, y)
        if c == 'w': assert rows[y - 1][x] in WATER or rows[y - 1][x] in SOLID, ('w sob o ar', x, y)
        if c in WATER: assert y + 1 < H and (rows[y + 1][x] in WATER or rows[y + 1][x] in SOLID), ('água flutuando', x, y)

def find(ch):
    return [(x, y) for y, r in enumerate(rows) for x, c in enumerate(r) if c == ch]
assert find('?') == [(50, 3), (12, 5), (171, 5)], find('?')
assert find('O') == [(110, 1)], find('O')
assert find('C') == [(48, 5), (103, 5)], find('C')

